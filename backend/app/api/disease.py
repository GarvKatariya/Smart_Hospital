from fastapi import APIRouter, Depends, HTTPException, status
from typing import Optional, Any
import logging
import uuid

from sqlalchemy.orm import Session
from app.api.deps import get_current_user, get_db
from app.schemas.ai import DiseasePredictionRequest, DiseasePredictionResponse
from app.db.models.user import User
from app.db.models.ai_models import DiseasePrediction

from app.services.disease_service import disease_service
from pydantic import BaseModel, Field

# Inline fallback schema in case the imported one differs
class FallbackDiseasePredictionRequest(BaseModel):
    age: float = Field(..., description="Age in years")
    sex: float = Field(..., description="1 = male, 0 = female")
    cp: float = Field(..., description="Chest pain type (0-3)")
    trestbps: float = Field(..., description="Resting blood pressure")
    chol: float = Field(..., description="Serum cholesterol")
    fbs: float = Field(..., description="Fasting blood sugar > 120 (1/0)")
    restecg: float = Field(..., description="Resting ECG results (0-2)")
    thalach: float = Field(..., description="Max heart rate")
    exang: float = Field(..., description="Exercise induced angina (1/0)")
    oldpeak: float = Field(..., description="ST depression induced by exercise")
    slope: float = Field(..., description="Slope of peak exercise ST segment (0-2)")
    ca: float = Field(..., description="Number of major vessels (0-3)")
    thal: float = Field(..., description="Thalassemia (0-3)")

class FallbackDiseasePredictionResponse(BaseModel):
    prediction: int
    probability: float
    risk_category: str
    feature_importance: dict
    model_version: str
    disclaimer: str

DiseaseReq = FallbackDiseasePredictionRequest
DiseaseRes = FallbackDiseasePredictionResponse

router = APIRouter(prefix="/api/disease", tags=["Disease Prediction"])
logger = logging.getLogger(__name__)

DISCLAIMER = (
    "This prediction is generated by a machine learning model trained on the UCI Heart Disease dataset. "
    "It is intended for educational and informational purposes only. "
    "This is NOT a medical diagnosis. Please consult a qualified healthcare professional "
    "for proper medical evaluation and diagnosis."
)


@router.post("/predict", response_model=DiseaseRes)
def predict_disease(
    request: DiseaseReq,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    try:
        features = request.dict()
        prediction_result = disease_service.predict(features)

        # Inject disclaimer
        prediction_result["disclaimer"] = DISCLAIMER

        # Persist result to DB
        try:
            db_record = DiseasePrediction(
                id=str(uuid.uuid4()),
                patient_id=current_user.id,
                input_features=features,
                prediction=str(prediction_result["prediction"]),
                probability=float(prediction_result["probability"]),
                risk_category=prediction_result["risk_category"],
                feature_importance=prediction_result["feature_importance"],
                model_version=prediction_result.get("model_version", "1.0"),
            )
            db.add(db_record)
            db.commit()
            logger.info(f"Disease prediction saved: {db_record.id}")
        except Exception as db_err:
            # Don't fail the request if DB write fails
            logger.error(f"Failed to save disease prediction to DB: {db_err}")
            db.rollback()

        return prediction_result

    except RuntimeError as e:
        logger.error(f"Prediction failed: {e}")
        raise HTTPException(status_code=status.HTTP_503_SERVICE_UNAVAILABLE, detail=str(e))
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="An unexpected error occurred during prediction.")
